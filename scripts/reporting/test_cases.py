"""The unit tests as formal test cases (the report's test-case template, Table 7.1), in Markdown and LaTeX.

  python -m scripts.reporting.test_cases [--specs docs/test/specs] [--out docs/test]

One test case per test class in tests/, one step per test method. Each class's description lives in
docs/test/specs/<test file>.json (component, references, objective, module, assumptions,
pre-requisites, per-step execution description and procedure result, comments). The rest is
measured, not typed:
  - status (Passed / Failed / Not Executed): the suite is run here, test by test;
  - test date: the day of this run;
  - test case version and revision history: the git history of the test file;
  - environment: this interpreter and its libraries.

Writes docs/test/README.md (the index), docs/test/test_cases.md and docs/test/test_cases.tex (the
same cases, LaTeX tables in the template's layout).
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import platform
import subprocess
import sys
import unittest
from pathlib import Path

ENGINEER = "Abi"
REVIEWER = "-"


def run_suite() -> dict[str, str]:
    """{'tests.test_x.Class.test_y': 'Passed' | 'Failed'} for every test in tests/."""
    suite = unittest.defaultTestLoader.discover("tests", top_level_dir=".")
    result = unittest.TestResult()
    suite.run(result)
    status = {}

    def walk(s):
        for t in s:
            if isinstance(t, unittest.TestSuite):
                walk(t)
            else:
                status[t.id()] = "Passed"
    walk(unittest.defaultTestLoader.discover("tests", top_level_dir="."))
    for t, _ in result.failures + result.errors:
        status[t.id()] = "Failed"
    for t, _ in result.skipped:
        status[t.id()] = "Not Executed"
    return status


def git_history(path: str) -> list[tuple[str, str]]:
    """[(date, short hash)] of the commits that touched the file, oldest first."""
    out = subprocess.run(["git", "log", "--follow", "--format=%ad %h", "--date=short", "--", path],
                         capture_output=True, text=True).stdout.split("\n")
    return [tuple(l.split()) for l in reversed(out) if l.strip()]


def environment() -> str:
    import numpy, pandas, scipy, sklearn
    libs = [f"Python {platform.python_version()}", f"NumPy {numpy.__version__}", f"SciPy {scipy.__version__}",
            f"scikit-learn {sklearn.__version__}", f"pandas {pandas.__version__}"]
    for name, mod in (("OpenCV", "cv2"), ("PyTorch", "torch")):
        try:
            libs.append(f"{name} {__import__(mod).__version__}")
        except ImportError:
            pass
    return (f"{platform.system()} {platform.release()} ({platform.version()}); conda environment fyp-local: "
            + ", ".join(libs) + ". CPU only; no GPU, dataset or model weights needed unless stated. "
            "Run from the repository root: python -m unittest discover -s tests -t .")


def head_commit() -> str:
    return subprocess.run(["git", "log", "-1", "--format=%h"], capture_output=True, text=True).stdout.strip()


def cases(specs: Path, status: dict[str, str]) -> list[dict]:
    out = []
    for f in sorted(specs.glob("test_*.json")):
        for c in json.loads(f.read_text(encoding="utf-8")):
            stem = Path(c["file"]).stem
            steps = []
            for s in c["steps"]:
                st = status.get(f"tests.{stem}.{c['class']}.{s['method']}", "Not Executed")
                steps.append({**s, "status": st})
            sts = {s["status"] for s in steps}
            c["status"] = "Failed" if "Failed" in sts else ("Not Executed" if sts == {"Not Executed"} else "Passed")
            c["steps"] = steps
            hist = git_history(c["file"])
            c["version"] = str(max(1, len(hist)))
            c["revisions"] = ("; ".join(f"v{i + 1} {d} ({h})" for i, (d, h) in enumerate(hist))
                              or "v1 (not yet committed)")
            out.append(c)
    for i, c in enumerate(out, 1):
        c["id"] = f"TC-{i:02d}"
    return out


# ---------- Markdown ----------

def md_escape(s: str) -> str:
    return str(s).replace("|", "\\|").replace("\n", " ")


def markdown(cs: list[dict], env: str, commit: str, date: str) -> str:
    lines = [f"# Test cases", "",
             f"*Generated by `python -m scripts.reporting.test_cases` on {date} from the specs in "
             f"`docs/test/specs/` and a run of the suite at commit `{commit}`. Edit the specs, not this file.*", ""]
    for c in cs:
        mark = {"Passed": "**[x] Passed** &nbsp; [ ] Failed &nbsp; [ ] Not Executed",
                "Failed": "[ ] Passed &nbsp; **[x] Failed** &nbsp; [ ] Not Executed",
                "Not Executed": "[ ] Passed &nbsp; [ ] Failed &nbsp; **[x] Not Executed**"}[c["status"]]
        refs = ", ".join(f"`{r}`" for r in c["references"]) + f"; `{c['file']}` `{c['class']}`"
        lines += [f"## {c['id']}: {md_escape(c['component'])}", "",
                  "| | | | |", "|---|---|---|---|",
                  f"| **Software component:** | {md_escape(c['component'])} | | |",
                  f"| **Reference:** | {md_escape(refs)} | | |",
                  f"| **Test Case ID:** | {c['id']} | **QA Test Engineer:** | {ENGINEER} |",
                  f"| **Test case Version:** | {c['version']} | **Reviewed By:** | {REVIEWER} |",
                  f"| **Test Date:** | {date} | **Use Case Reference(s):** | {md_escape(c['design_refs'])} |",
                  f"| **Revision History:** | {md_escape(c['revisions'])} | | |",
                  f"| **Objective:** | {md_escape(c['objective'])} | | |",
                  f"| **Product/Ver/Module:** | FYP-1 attention pipeline, commit `{commit}`. {md_escape(c['module'])} | | |",
                  f"| **Environment:** | {md_escape(env)} | | |",
                  f"| **Assumptions:** | {md_escape(c['assumptions'])} | | |",
                  f"| **Pre-Requisite:** | {md_escape(c['prerequisites'])} | | |", "",
                  "| Step No. | Execution description | Procedure result |", "|---|---|---|"]
        for i, s in enumerate(c["steps"], 1):
            lines.append(f"| {i} | `{s['method']}`: {md_escape(s['execution'])} | "
                         f"{md_escape(s['result'])} ({s['status']}) |")
        lines += ["", f"**Comments:** {md_escape(c['comments'])}", "", mark, "", "---", ""]
    return "\n".join(lines)


def index(cs: list[dict], commit: str, date: str, total: int, passed: int) -> str:
    lines = ["# Tests", "",
             "The unit tests (`tests/`), documented as test cases in the report's template (Table 7.1): one",
             "test case per test class, one step per test method.", "",
             f"- **Last run:** {date}, commit `{commit}`: **{passed} of {total} tests passed**.",
             "- **Run them:** `python -m unittest discover -s tests -t .` from the repository root.",
             "- **The cases:** [test_cases.md](test_cases.md); the same in LaTeX for the report:",
             "  [test_cases.tex](test_cases.tex) (`\\input{}` it; needs the `array` package).",
             "- **Regenerate** after changing tests: `python -m scripts.reporting.test_cases`. The descriptions",
             "  come from `specs/<test file>.json`; status, dates, versions and the environment are measured.", "",
             "| ID | Component | Test class | Steps | Status |", "|---|---|---|---|---|"]
    for c in cs:
        lines.append(f"| {c['id']} | {md_escape(c['component'])} | `{c['file']}` `{c['class']}` | "
                     f"{len(c['steps'])} | {c['status']} |")
    return "\n".join(lines) + "\n"


# ---------- LaTeX ----------

TEX_MAP = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_",
           "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}",
           "≥": r"$\geq$", "≤": r"$\leq$", "×": r"$\times$", "−": "-", "±": r"$\pm$", "§": r"\S{}",
           "ρ": r"$\rho$", "α": r"$\alpha$", "σ": r"$\sigma$", "→": r"$\rightarrow$", "≈": r"$\approx$",
           "–": "--", "—": "---", "’": "'", "‘": "`", "“": "``", "”": "''", "…": r"\ldots{}", "√": r"$\surd$",
           "²": r"$^2$", "µ": r"$\mu$", "·": r"$\cdot$", "≠": r"$\neq$", "°": r"$^\circ$"}


def tex(s: str) -> str:
    out = []
    for ch in str(s):
        if ch in TEX_MAP:
            out.append(TEX_MAP[ch])
        elif ord(ch) < 128:
            out.append(ch)
        else:
            out.append("?")
    # paths and identifiers may break after an underscore or a slash
    return "".join(out).replace(r"\_", r"\_\allowbreak{}").replace("/", r"/\allowbreak{}")


def tex_code(s: str) -> str:
    """A method name for \texttt, allowed to break after each underscore."""
    return tex(s)


WIDTHS = (0.21, 0.27, 0.17, 0.19)  # the four base columns, as shares of \linewidth (with padding < 1)


def width(first: int, last: int) -> str:
    """Width of a cell spanning base columns first..last (0-based): their widths plus the padding and
    rules between them, so spanned cells line up exactly with the rows of four."""
    k = last - first
    w = round(sum(WIDTHS[first:last + 1]), 2)
    return (r"\dimexpr " + f"{w}" + r"\linewidth+" + f"{2 * k}" + r"\tabcolsep+" + f"{k}" + r"\arrayrulewidth\relax"
            if k else f"{w}" + r"\linewidth")


WIDE = "L{" + width(1, 3) + "}"    # the value cell spanning columns 2-4
HALF = "L{" + width(2, 3) + "}"    # the procedure-result cell spanning columns 3-4
FULL = "L{" + width(0, 3) + "}"    # comments, spanning all four
TITLE = "C{" + width(0, 3) + "}"   # centred title rows, wrapped when long


def latex(cs: list[dict], env: str, commit: str, date: str) -> str:
    cols = "|" + "|".join("L{" + width(i, i) + "}" for i in range(4)) + "|"
    parts = [f"% Generated by `python -m scripts.reporting.test_cases` on {date} (commit {commit}).",
             "% One table per test case, in the layout of the report's Table 7.1.",
             r"% Needs \usepackage{array,longtable} in the preamble.",
             r"\newcolumntype{L}[1]{>{\raggedright\arraybackslash}p{#1}}",
             r"\newcolumntype{C}[1]{>{\centering\arraybackslash}p{#1}}", ""]

    def span(label: str, value: str) -> str:
        return r"\textbf{" + label + r"} & \multicolumn{3}{" + WIDE + "|}{" + value + r"} \\ \hline"

    for c in cs:
        refs = ", ".join(c["references"]) + f"; {c['file']} ({c['class']})"
        mark = r" \quad ".join((r"\fbox{" + st + "}" if st == c["status"] else st)
                               for st in ("Passed", "Failed", "Not Executed"))
        rows = [
            r"\multicolumn{4}{|" + TITLE + r"|}{\textbf{" + tex(c["component"]) + r"}} \\ \hline",
            r"\multicolumn{4}{|" + TITLE + r"|}{\textbf{" + tex(refs) + r"}} \\ \hline",
            r"\textbf{Test Case ID:} & " + tex(c["id"]) + r" & \textbf{QA Test Engineer:} & " + tex(ENGINEER) + r" \\ \hline",
            r"\textbf{Test case Version:} & " + tex(c["version"]) + r" & \textbf{Reviewed By:} & " + tex(REVIEWER) + r" \\ \hline",
            r"\textbf{Test Date:} & " + tex(date) + r" & \textbf{Use Case Reference(s):} & " + tex(c["design_refs"]) + r" \\ \hline",
            span("Revision History:", tex(c["revisions"])),
            span("Objective:", tex(c["objective"])),
            span("Product/Ver/ Module:", "FYP-1 attention pipeline, commit " + tex(commit) + ". " + tex(c["module"])),
            span("Environment:", tex(env)),
            span("Assumptions:", tex(c["assumptions"])),
            span("Pre-Requisite:", tex(c["prerequisites"])),
            r"\textbf{Step No.} & \textbf{Execution description} & \multicolumn{2}{" + HALF + r"|}{\textbf{Procedure result}} \\ \hline",
        ]
        for i, st in enumerate(c["steps"], 1):
            rows.append(f"{i} & " + r"\texttt{" + tex_code(st["method"]) + "}: " + tex(st["execution"])
                        + r" & \multicolumn{2}{" + HALF + "|}{" + tex(st["result"]) + " (" + tex(st["status"]) + r")} \\ \hline")
        rows += [r"\multicolumn{4}{|" + FULL + r"|}{\textbf{Comments:} " + tex(c["comments"]) + r"} \\ \hline",
                 r"\multicolumn{4}{|" + TITLE + r"|}{\textbf{" + mark + r"}} \\ \hline"]
        parts += [r"\begin{longtable}{" + cols + "}",
                  r"\caption{Test case " + tex(c["id"]) + ": " + tex(c["component"]) + r"}\label{tab:"
                  + c["id"].lower() + r"} \\ \hline",
                  *rows, r"\end{longtable}", ""]
    return "\n".join(parts)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--specs", default="docs/test/specs")
    ap.add_argument("--out", default="docs/test")
    args = ap.parse_args()
    status = run_suite()
    date, commit, env = dt.date.today().isoformat(), head_commit(), environment()
    cs = cases(Path(args.specs), status)
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    (out / "test_cases.md").write_text(markdown(cs, env, commit, date), encoding="utf-8")
    (out / "test_cases.tex").write_text(latex(cs, env, commit, date), encoding="utf-8")
    passed = sum(v == "Passed" for v in status.values())
    (out / "README.md").write_text(index(cs, commit, date, len(status), passed), encoding="utf-8")
    documented = sum(len(c["steps"]) for c in cs)
    print(f"{len(cs)} test cases, {documented} steps documented; {passed}/{len(status)} tests passed")
    missing = set(status) - {f"tests.{Path(c['file']).stem}.{c['class']}.{s['method']}" for c in cs for s in c["steps"]}
    if missing:
        print(f"{len(missing)} tests have no spec yet:", *sorted(missing)[:10], sep="\n  ")


if __name__ == "__main__":
    sys.exit(main())
